#!/usr/bin/env python3
"""Byte-level comparison of archived alioth PM855GUI Gen4 battery profiles."""
from pathlib import Path
import csv
import re

ROOT = Path(__file__).resolve().parents[1]
BAT = ROOT / "research/battery"
PROFILES = {
    "FMT-4520": BAT / "alioth-FMT-4520mah.dtsi",
    "GY-4520": BAT / "alioth-GY-4520mah.dtsi",
    "J3S-Sun-5000": BAT / "alioth-J3S-Sun-5000mah.dtsi",
}
PROVISION = BAT / "J3S-Sun-5000mah.BATTERY.PROVISION2"
OUT = BAT / "Gen4-Comparison"

def parse_profile(path):
    text = path.read_text(encoding="utf-8")
    match = re.search(r"qcom,fg-profile-data\s*=\s*\[([\s\S]*?)\]", text)
    if not match:
        raise ValueError(f"{path.name}: qcom,fg-profile-data missing")
    payload = bytes(int(x, 16) for x in re.findall(r"\b[0-9A-Fa-f]{2}\b", match.group(1)))
    if len(payload) != 416:
        raise ValueError(f"{path.name}: expected 416 bytes, got {len(payload)}")
    def prop(pattern):
        hit = re.search(pattern, text)
        return hit.group(1).strip() if hit else "not stated"
    return {
        "bytes": payload,
        "capacity_mAh": prop(r"qcom,nom-batt-capacity-mah\s*=\s*<([0-9]+)>"),
        "max_voltage_uV": prop(r"qcom,max-voltage-uv\s*=\s*<([0-9]+)>"),
        "battery_id_kohm": prop(r"qcom,batt-id-kohm\s*=\s*<([0-9]+)>"),
        "battery_type": prop(r'qcom,battery-type\s*=\s*"([^"]+)"'),
        "rslow_normal": prop(r"qcom,rslow-normal-coeffs\s*=\s*<([^>]+)>"),
        "rslow_low": prop(r"qcom,rslow-low-coeffs\s*=\s*<([^>]+)>"),
        "checksum": prop(r"qcom,checksum\s*=\s*<([^>]+)>"),
        "gui": prop(r'qcom,gui-version\s*=\s*"([^"]+)"'),
    }

def parse_provision(path):
    text = path.read_text(encoding="utf-8")
    rows = {}
    pattern = r"^\s*([0-9A-Fa-f]{3}),\s*[0-9A-Fa-f]{3},\s*([01]),\s*([0-9A-Fa-f]{2})\s*$"
    for m in re.finditer(pattern, text, re.M):
        rows[(int(m.group(1), 16), int(m.group(2)))] = int(m.group(3), 16)
    ordered = []
    for addr in range(0x041, 0x110):
        for offset in (0, 1):
            if (addr, offset) in rows:
                ordered.append(rows[(addr, offset)])
    return bytes(ordered), rows

def main():
    profiles = {name: parse_profile(path) for name, path in PROFILES.items()}
    provision, rows = parse_provision(PROVISION)
    j3s = profiles["J3S-Sun-5000"]["bytes"]
    if len(provision) != 414:
        raise SystemExit(f"FAIL: provision has {len(provision)} mapped bytes, expected 414")
    if provision != j3s[:414] or j3s[414:] != b"\x00\x00":
        raise SystemExit("FAIL: J3S provision does not match DTSI payload")
    if len(rows) != 414:
        raise SystemExit(f"FAIL: expected 414 address/offset entries, got {len(rows)}")

    OUT.mkdir(parents=True, exist_ok=True)
    with (OUT / "register-byte-comparison.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["payload_index", "register_address", "byte_offset", *profiles.keys(), "distinct_values"])
        for i in range(416):
            vals = [p["bytes"][i] for p in profiles.values()]
            address = 0x041 + i // 2 if i < 414 else None
            offset = i % 2 if i < 414 else "n/a"
            w.writerow([i, f"0x{address:03X}" if address is not None else "unmapped-tail",
                        offset, *[f"0x{x:02X}" for x in vals], len(set(vals))])

    with (OUT / "profile-metadata.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["profile", "capacity_mAh", "max_voltage_uV", "battery_id_kohm",
                    "battery_type", "rslow_normal", "rslow_low", "checksum", "gui"])
        for name, p in profiles.items():
            w.writerow([name, p["capacity_mAh"], p["max_voltage_uV"], p["battery_id_kohm"],
                        p["battery_type"], p["rslow_normal"], p["rslow_low"], p["checksum"], p["gui"]])

    differing = sum(len({p["bytes"][i] for p in profiles.values()}) > 1 for i in range(416))
    common = 416 - differing
    lines = [
        "# Alioth PM855GUI Gen4 byte comparison", "",
        "Generated by tools/compare_alioth_gen4_profiles.py. Payloads are opaque 416-byte PM855GUI exports; no undocumented register meaning or electrical unit is inferred.", "",
        "## Source profiles", "",
        "| Profile | Nominal capacity | Max voltage | Battery ID | Type | Checksum |",
        "|---|---:|---:|---:|---|---|",
    ]
    for name, p in profiles.items():
        lines.append(f"| {name} | {p['capacity_mAh']} mAh | {p['max_voltage_uV']} µV | {p['battery_id_kohm']} kΩ | {p['battery_type']} | {p['checksum']} |")
    lines += [
        "", "## Byte-level result", "",
        "- Payload length: 416 bytes for each profile.",
        f"- Byte positions identical across all three profiles: {common}.",
        f"- Byte positions differing in at least one profile: {differing}.",
        "- Mapped provision range: registers 0x041–0x10F, offsets 0 and 1 (414 bytes).",
        "- J3S provision export matches J3S DTSI bytes 0–413 exactly.",
        "- J3S DTSI retains two trailing bytes 00 00 beyond the available provision address rows.",
        "- For indices 0–413, register address is 0x041 + index // 2; byte offset is index % 2.",
        "- distinct_values counts unique byte values at each index across FMT, GY and J3S.",
        "", "## Interpretation limits", "",
        "FMT and GY are alioth Gen4 reference profiles at 4520 mAh; J3S Sun is an alioth Gen4 reference at 5000 mAh. These are comparison references, not BN61 data.",
        "Capacity, voltage, battery ID, battery type, Rslow and checksum are copied from DTSI declarations. Individual semantics of the 416-byte payload remain undocumented here.",
        "No BN61/5850 mAh payload is generated. Scaling or interpolating these bytes is not a valid electrical characterization.",
        "", "## Reproducibility", "", "Run: python3 tools/compare_alioth_gen4_profiles.py",
        "Outputs: register-byte-comparison.csv and profile-metadata.csv in this directory.",
        "J3S provision cross-check: PASS (414 explicit bytes plus two trailing zero bytes in DTSI).",
    ]
    (OUT / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"PASS: three Gen4 profiles parsed (416 bytes each); {common} common positions, {differing} differing.")
    print("PASS: J3S PM855GUI provision matches payload bytes 0..413; trailing DTSI bytes are 00 00.")
    print(f"Reports written to {OUT.relative_to(ROOT)}")

if __name__ == "__main__":
    main()
